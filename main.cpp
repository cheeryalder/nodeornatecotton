#include <string>
#include <vector>

void count_vowels() {
    std::string text = "prism bridge";
    int vowels = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        char ch = text[i];
        if (ch == 'a' || ch == 'e' || ch == 'i' || ch == 'o' || ch == 'u') vowels += 1;
    }
    (void)vowels;
}

void merge_text() {
    std::string a = "quiet";
    std::string b = "stone";
    std::string joined = a + "_" + b;
    (void)joined;
}

void arithmetic_sum() {
    int first = 3, diff = 4, count = 9;
    int last = first + diff * (count - 1);
    int total = (first + last) * count / 2;
    (void)total;
}

void reverse_digits() {
    int n = 12345;
    int reversed = 0;
    while (n > 0) {
        reversed = reversed * 10 + (n % 10);
        n /= 10;
    }
    (void)reversed;
}

extern "C" int sable_orbit();
extern "C" void still_summit();
extern "C" void eager_boulder();
extern "C" void prime_bridge();
extern "C" void radiant_willow();

int main() {
    count_vowels();
    merge_text();
    arithmetic_sum();
    reverse_digits();
    still_summit();
    eager_boulder();
    prime_bridge();
    radiant_willow();
    return sable_orbit();
}
